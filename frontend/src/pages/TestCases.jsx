import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { Plus } from 'lucide-react';
import { getTestCases } from '../api';
import StatusBadge from '../components/StatusBadge';
import { Card, CardContent } from '@/components/ui/card';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table';
import { Input } from '@/components/ui/input';
import { Button } from '@/components/ui/button';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import TablePagination from '../components/table-pagination';

const ALL = '__all__';

function FilterSelect({ value, onChange, placeholder, options }) {
  return (
    <Select value={value || ALL} onValueChange={(v) => onChange(v === ALL ? '' : v)}>
      <SelectTrigger className="w-40">
        <SelectValue placeholder={placeholder} />
      </SelectTrigger>
      <SelectContent>
        <SelectItem value={ALL}>{placeholder}</SelectItem>
        {options.map((opt) => (
          <SelectItem key={opt.value} value={opt.value}>
            {opt.label}
          </SelectItem>
        ))}
      </SelectContent>
    </Select>
  );
}

export default function TestCases() {
  const [data, setData] = useState(null);
  const [page, setPage] = useState(1);
  const [project, setProject] = useState('');
  const [suite, setSuite] = useState('');
  const [source, setSource] = useState('');
  const [format, setFormat] = useState('');
  const [priority, setPriority] = useState('');
  const [status, setStatus] = useState('');

  useEffect(() => {
    setPage(1);
  }, [project, suite, source, format, priority, status]);

  useEffect(() => {
    getTestCases({
      page,
      limit: 15,
      project: project || undefined,
      suite: suite || undefined,
      source: source || undefined,
      format: format || undefined,
      priority: priority || undefined,
      status: status || undefined
    }).then(setData);
  }, [page, project, suite, source, format, priority, status]);

  const totalPages = data ? Math.ceil(data.total / data.limit) : 1;

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h2 className="text-lg font-semibold">Test Cases</h2>
          <p className="text-sm text-muted-foreground">
            Test case definitions created manually or generated by an AI assistant through the MCP server.
          </p>
        </div>
        <Button asChild>
          <Link to="/testcases/new">
            <Plus /> New test case
          </Link>
        </Button>
      </div>

      <div className="flex flex-wrap gap-2">
        <Input placeholder="Project" value={project} onChange={(e) => setProject(e.target.value)} className="w-40" />
        <Input placeholder="Suite" value={suite} onChange={(e) => setSuite(e.target.value)} className="w-40" />
        <FilterSelect
          value={source}
          onChange={setSource}
          placeholder="All sources"
          options={[
            { value: 'ai-generated', label: 'AI-generated (MCP)' },
            { value: 'manual', label: 'Manual' }
          ]}
        />
        <FilterSelect
          value={format}
          onChange={setFormat}
          placeholder="All formats"
          options={[
            { value: 'manual', label: 'Manual' },
            { value: 'cucumber', label: 'Cucumber' }
          ]}
        />
        <FilterSelect
          value={priority}
          onChange={setPriority}
          placeholder="All priorities"
          options={[
            { value: 'low', label: 'Low' },
            { value: 'medium', label: 'Medium' },
            { value: 'high', label: 'High' },
            { value: 'critical', label: 'Critical' }
          ]}
        />
        <FilterSelect
          value={status}
          onChange={setStatus}
          placeholder="All statuses"
          options={[
            { value: 'draft', label: 'Draft' },
            { value: 'active', label: 'Active' },
            { value: 'deprecated', label: 'Deprecated' }
          ]}
        />
      </div>

      <Card>
        <CardContent className="p-0">
          {data?.testCases?.length ? (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>ID</TableHead>
                  <TableHead>Title</TableHead>
                  <TableHead>Format</TableHead>
                  <TableHead>Project / Suite</TableHead>
                  <TableHead>Priority</TableHead>
                  <TableHead>Status</TableHead>
                  <TableHead>Source</TableHead>
                  <TableHead>Tags</TableHead>
                  <TableHead>Created</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {data.testCases.map((tc) => (
                  <TableRow key={tc._id}>
                    <TableCell className="whitespace-nowrap font-mono text-xs text-muted-foreground">
                      {tc.testCaseId || '—'}
                    </TableCell>
                    <TableCell>
                      <Link to={`/testcases/${tc._id}`} className="font-medium text-primary hover:underline">
                        {tc.title}
                      </Link>
                    </TableCell>
                    <TableCell>
                      <StatusBadge status={tc.format || 'manual'} />
                    </TableCell>
                    <TableCell className="text-muted-foreground">
                      {tc.project} / {tc.suite}
                    </TableCell>
                    <TableCell>
                      <StatusBadge status={tc.priority} />
                    </TableCell>
                    <TableCell>
                      <StatusBadge status={tc.status} />
                    </TableCell>
                    <TableCell>
                      <StatusBadge status={tc.source} />
                    </TableCell>
                    <TableCell className="text-muted-foreground">{tc.tags?.join(', ') || '—'}</TableCell>
                    <TableCell className="text-muted-foreground">{new Date(tc.createdAt).toLocaleDateString()}</TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          ) : (
            <div className="p-8 text-center text-sm text-muted-foreground">No test cases yet.</div>
          )}
        </CardContent>
      </Card>

      {data && (
        <TablePagination
          page={page}
          totalPages={totalPages}
          onPageChange={setPage}
          totalItems={data.total}
          itemLabel="test cases"
        />
      )}
    </div>
  );
}
